    public static string BuildTitle(string contrast, string noun) => $"{noun} {ContrastWord[contrast]}";

    public static string BuildSubtitle(int variant, string family, string undertone, string contrast, string noun)
    {
        var moodFeminine = SeasonMoodFeminine[family];
        var undertoneWord = UndertoneWord[undertone];
        var undertoneFeminine = UndertoneWordFeminine[undertone];
        var contrastLower = ContrastLevel[contrast];
        var familyLower = FamilyName[family];
        var nounLower = noun;
        var contrastDescFeminine = ContrastDescriptorFeminine[contrast];

        return variant switch
        {
            0 => $"درجات {moodFeminine}، مضبوطة على باليتك {undertoneWord} ذات التباين {contrastLower}",
            1 => $"درجات {Capitalize(contrastDescFeminine)}، لإشراقتك {undertoneFeminine}",
            2 => $"طاقة {noun}، خاصة بباليت {familyLower}",
            3 => $"تشكيلة {Capitalize(undertoneFeminine)} بتباين {contrastLower}، مستوحاة من {nounLower}",
            4 => $"أسلوب اليوم بلمسة {familyLower} وتباين {contrastLower}",
            _ => $"اختيار لومي بدرجة {undertoneFeminine}، بلمسات من {nounLower}"
        };
    }

    public static string BuildDescription(string family, string undertone, string contrast, string noun)
    {
        var moodLower = SeasonMood[family];
        var undertoneAdjective = UndertoneAdjective[undertone];
        var contrastDescFeminine = ContrastDescriptorFeminine[contrast];

        return $"ضوء اليوم {moodLower} — فمالت لومي نحو {noun} لتحافظ على إشراقتك {undertoneAdjective} {contrastDescFeminine}.";
    }

    private static string Capitalize(string value) =>
        string.IsNullOrEmpty(value) ? value : char.ToUpperInvariant(value[0]) + value[1..];
