    public static string BuildTitle(string contrast, string noun) => $"{ContrastWord[contrast]} {noun}";

    // Undertone/contrast/family words are inserted as quoted labels («тёплый», «высокий», ...)
    // rather than as directly-agreeing adjectives — Russian's gender/case system means a single
    // base form can't correctly modify every noun these subtitles reference (palette is feminine,
    // glow is neuter, tone is masculine, ...); quoting sidesteps the agreement mismatch while
    // staying natural, idiomatic Russian marketing phrasing.
    public static string BuildSubtitle(int variant, string family, string undertone, string contrast, string noun)
    {
        var mood = SeasonMood[family];
        var undertoneLower = UndertoneWord[undertone];
        var contrastLower = ContrastLevel[contrast];
        var familyLower = FamilyName[family];
        var contrastDesc = ContrastDescriptor[contrast];

        return variant switch
        {
            0 => $"Оттенки «{mood}» — тон «{undertoneLower}», контраст «{contrastLower}»",
            1 => $"{Capitalize(contrastDesc)} — акцент для тона «{undertoneLower}»",
            2 => $"Энергия «{noun}» — создана для палитры сезона «{familyLower}»",
            3 => $"Тон «{undertoneLower}», контраст «{contrastLower}» — подборка в духе «{noun}»",
            4 => $"Сезон «{familyLower}», контраст «{contrastLower}» — стиль дня",
            _ => $"Выбор Lumi для тона «{undertoneLower}» — с оттенком «{noun}»"
        };
    }

    public static string BuildDescription(string family, string undertone, string contrast, string noun)
    {
        var moodLower = SeasonMood[family].ToLowerInvariant();
        var undertoneAdjective = UndertoneAdjective[undertone];
        var contrastDescInstrumental = ContrastDescriptorInstrumental[contrast];

        return $"Сегодняшний свет — {moodLower}. Lumi выбрала оттенок «{noun}», чтобы твой образ оставался {contrastDescInstrumental} — {undertoneAdjective}.";
    }

    private static string Capitalize(string value) =>
        string.IsNullOrEmpty(value) ? value : char.ToUpperInvariant(value[0]) + value[1..];
}
